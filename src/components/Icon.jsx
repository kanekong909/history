// Icono según el nombre de la categoría (si no hay coincidencia, un marcapáginas).
export function categoryIcon(name = '') {
  const n = name.toLowerCase()
  if (/histor|pasado|guerra|époc|epoc/.test(n)) return 'history'
  if (/viaj|turis|lugar|ciudad|paisaj/.test(n)) return 'compass'
  if (/recet|cocin|comida|gastron/.test(n)) return 'food'
  if (/relat|cuent|poes|carta|novela|escrit/.test(n)) return 'feather'
  if (/foto|imagen|arte/.test(n)) return 'camera'
  if (/music|músic|canci/.test(n)) return 'music'
  return 'bookmark'
}

